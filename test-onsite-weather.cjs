const assert=require('node:assert/strict'),fs=require('node:fs');
const {assess}=require('./dist/onsite.js');
const limits={maxwind:12,opwind:10,mintemp:-10,maxtemp:40,minvis:500,maxrain:0};
const review={status:'acceptable',reviewedAt:'2026-11-18T12:00:00Z',conditions:{},note:''};
assert.equal(assess(review,limits).valid,true);
for(const status of ['unreviewed','uncertain','unacceptable'])assert.equal(assess({...review,status},limits).valid,false);
for(const status of ['uncertain','unacceptable'])assert.equal(assess({...review,status},limits).complete,true,'Unsafe/uncertain recorded assessment is complete, while remaining operationally invalid');
assert.equal(assess({...review,status:'unreviewed'},limits).complete,false);
assert.equal(assess({...review,conditions:{wind:-1}},limits).complete,false);
assert.equal(assess({...review,conditions:{wind:15}},limits).complete,true);
assert.equal(assess({...review,reviewedAt:null},limits).valid,false);
for(const conditions of [{wind:10},{gust:11},{temperature:41},{temperature:-11},{visibility:499},{wind:-1},{visibility:-1},{rain:-0.1},{rain:0.1}])assert.equal(assess({...review,conditions},limits).valid,false);
assert.equal(assess({...review,conditions:{wind:9,gust:9.9,temperature:20,visibility:600}},limits).valid,true);
assert.equal(assess({...review,conditions:{rain:0}},limits).valid,true);
assert.equal(assess({...review,conditions:{rain:null}},limits).valid,true);
assert.equal(assess({...review,conditions:{rain:0.5}},{...limits,maxrain:0.6}).valid,true);
assert(assess({...review,conditions:{rain:0.7}},{...limits,maxrain:0.6}).reasons.some(r=>r.includes('precipitation')));
const onsite=fs.readFileSync('dist/onsite.js','utf8');
assert(onsite.includes("forecast.id='weatherforecastsection'")&&onsite.includes("wrap.id='onsitepanel'"));
assert(onsite.includes("['rain','Precipitation','mm/h']"));
assert(onsite.includes("precipitationReference.id='precipitationreference'"));
assert(!onsite.includes('<details><summary>Optional observations'));
const map=fs.readFileSync('dist/weather-map.js','utf8'),html=fs.readFileSync('dist/index.html','utf8');
assert(!/sessionKey|customer-api|wxkey|wxlink|bookmarkKey/.test(map));
assert(!/id="wx(key|link)|Paid subscriptions and weather-service links/.test(html));
assert(map.includes('https://api.open-meteo.com/v1/forecast?'));
assert(map.includes('radareligible')&&html.includes('RainViewer API terms'));
assert(map.includes('legend()')&&map.includes('Geo.leaflet(point)'));
console.log('On-site conditions: assessment, actual-limit blockers, unknown states, public-only weather and preserved radar/legend checks passed');
